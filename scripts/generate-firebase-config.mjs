import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const localFile = new URL('.env.local', root);
const local = {};
if (existsSync(localFile)) {
  for (const [index, line] of readFileSync(localFile, 'utf8').split(/\r?\n/).entries()) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const match = line.match(/^\s*(?:export\s+)?([A-Z_][A-Z_0-9]*)\s*=\s*(.*?)\s*$/);
    if (!match) throw new Error(`Invalid .env.local entry on line ${index + 1}. Use KEY=value.`);
    let value = match[2];
    if (value.startsWith('"') || value.startsWith("'")) {
      const quote = value[0];
      const end = value.indexOf(quote, 1);
      if (end < 0 || !/^\s*(?:#.*)?$/.test(value.slice(end + 1))) {
        throw new Error(`Invalid quoted .env.local value on line ${index + 1}.`);
      }
      value = value.slice(1, end);
    } else {
      value = value.replace(/\s+#.*$/, '').trim();
    }
    local[match[1]] = value;
  }
}

const fields = {
  apiKey: 'FIREBASE_API_KEY',
  authDomain: 'FIREBASE_AUTH_DOMAIN',
  projectId: 'FIREBASE_PROJECT_ID',
  storageBucket: 'FIREBASE_STORAGE_BUCKET',
  messagingSenderId: 'FIREBASE_MESSAGING_SENDER_ID',
  appId: 'FIREBASE_APP_ID',
  measurementId: 'FIREBASE_MEASUREMENT_ID'
};
const config = {};
const missing = [];
for (const [field, variable] of Object.entries(fields)) {
  const value = (process.env[variable] ?? local[variable] ?? '').trim();
  if (field !== 'measurementId' && (!value || value.startsWith('YOUR_'))) missing.push(variable);
  config[field] = value;
}
if (missing.length) {
  throw new Error(`Missing Firebase configuration: ${missing.join(', ')}. Set these in .env.local (see .env.example) or the build environment.`);
}
const output = new URL('src/environments/firebase.config.generated.ts', root);
writeFileSync(output, '// Generated by scripts/generate-firebase-config.mjs. Do not commit.\n' +
  "import type { FirebaseConfig } from './firebase.config';\n\n" +
  `export const firebaseConfig: FirebaseConfig = ${JSON.stringify(config, null, 2)};\n`);
console.log(`Generated ${fileURLToPath(output)}`);
